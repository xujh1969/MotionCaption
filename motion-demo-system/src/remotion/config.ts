/** 生成某组件配置的默认值对象 */
export function defaultConfig(id: string): ConfigState {
  const base = (CONFIGS[id] ?? []).reduce<ConfigState>((acc, d) => {
    acc[d.key] = d.default;
    return acc;
  }, {});
  const ov = DEFAULTS[id];
  if (ov) {
    for (const k of Object.keys(base)) {
      if (ov[k] !== undefined) base[k] = ov[k];
    }
  }
  return base;
}

const ConfigCtx = createContext<ConfigState>({});

/** 读取配置：优先取 `<组件id>::<key>`（用于复合组件定向控制子组件），
 *  其次取全局 `<key>`（直接组件），最后回退该组件默认值 */
export function useConfigKey(id: string, key: string): number | string {
  const ctx = useContext(ConfigCtx);
  const scoped = ctx[`${id}::${key}`];
  if (scoped !== undefined && scoped !== '') return scoped;
  const plain = ctx[key];
  if (plain !== undefined && plain !== '') return plain;
  return CONFIGS[id]?.find((x) => x.key === key)?.default ?? 0;
}

export const ConfigProvider = ConfigCtx.Provider;

/** 读取 list 型(数据条目)配置，返回对象数组；出错时回退空数组 */
export function useConfigList(id: string, key: string): Record<string, string>[] {
  const raw = useConfigKey(id, key);
  if (Array.isArray(raw)) return raw as unknown as Record<string, string>[];
  if (typeof raw === 'string' && raw.trim()) {
    try {
      const j = JSON.parse(raw);
      if (Array.isArray(j)) return j;
    } catch {
      /* 忽略解析错误 */
    }
  }
  return [];
}

